def __getattr__(name: str) -> object:
    if name in _GAME_STACK_EXPORTS:
        module = import_module("sim.flight_software.game_stacks")
    elif name in _PROFILE_EXPORTS:
        module = import_module("sim.flight_software.profiles")
    elif name in _CATALOG_EXPORTS:
        module = import_module("sim.flight_software.catalog")
    elif name in _REFERENCE_STACK_EXPORTS:
        module = import_module("sim.flight_software.reference_stacks")
    else:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    value = getattr(module, name)
    globals()[name] = value
    return value
