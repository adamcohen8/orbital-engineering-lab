def test_contours_update_geometry_without_accumulating_artists():
    import matplotlib.pyplot as plt

    from sim.review.cr3bp import _ZeroVelocityContours

    u, v = np.meshgrid(np.linspace(-2, 2, 31), np.linspace(-2, 2, 31))
    fig, ax = plt.subplots()
    try:
        contours = _ZeroVelocityContours(ax, u, v, u)
        for c in [0.0, 1.0, -1.0, 1.0, 0.0]:
            contours.update(c)
            assert len(ax.collections) == 2
            line = contours.artists[1].get_paths()[0].vertices
            np.testing.assert_allclose(line[:, 0], c, atol=1e-14)
        contours.update(-3.0)  # Entire domain allowed; no zero contour.
        assert len(ax.collections) == 1
        contours.update(3.0)  # Entire domain forbidden.
        assert len(ax.collections) == 1
        contours.update(0.0)  # Contour reappears on rewind/contact-sheet selection.
        assert len(ax.collections) == 2
    finally:
        plt.close(fig)


@pytest.mark.parametrize("mode", ["fixed", "instantaneous"])
def test_maneuver_movie_uses_sample_jacobi(workspace, mode):
    from sim.dynamics.orbit.cr3bp_research import cr3bp_jacobi_constant
    from sim.review.cr3bp import load_cr3bp_history

    # This database is a synthetic test fixture, generated by OEL propagation.
    state = cr3bp_halo_seed_state_km_s(family="l1_northern_large")
    with sqlite3.connect(workspace.db_path) as conn:
        conn.execute("DELETE FROM object_state")
        for t in np.arange(0.0, 7201.0, 300.0):
            conn.execute("INSERT INTO object_state VALUES (?, ?, ?, ?, ?, ?, ?, ?)", ["vehicle", t, *state])
            accel = np.array([0.0, 5e-5, 0.0]) if 1800 <= t < 5400 else np.zeros(3)
            state = propagate_cr3bp_state(state, 300.0, t, accel, integrator="rkf78")
    times, states, system = load_cr3bp_history(workspace, "vehicle")
    c = cr3bp_jacobi_constant(states, system=system)
    assert np.ptp(c) > 0.01
    np.testing.assert_allclose(c[:7], c[0], atol=1e-12, rtol=0)
    np.testing.assert_allclose(c[18:], c[18], atol=1e-12, rtol=0)
    result = render_cr3bp_research(
        workspace,
        "vehicle",
        kind="zero_velocity",
        jacobi_mode=mode,
        movie_format="gif",
        frames=7,
        fps=3,
        resolution=61,
        bounds_km=(-600000, 600000, -600000, 600000),
    )
    receipt = json.loads(Path(result["receipt"]).read_text())
    indices = receipt["movie_sample_indices"]
    expected = c[indices] if mode == "instantaneous" else np.full(7, c[0])
    np.testing.assert_allclose(receipt["movie_jacobi_values"], expected)
    np.testing.assert_array_equal(receipt["movie_frame_times_s"], times[indices])
    assert receipt["movie_qa"]["automated_status"] == "passed"


