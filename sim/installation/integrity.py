"""Signed source and managed-runtime inventories for OEL installations.

The installation record and ``installed-tree.json`` are deliberately mutable
state.  They are useful diagnostics, but they are not an authority for an
official installation.  This module builds the content that is signed in a
release manifest and verifies an installed tree against that signed content.

The inventory is intentionally conservative.  It records exact source bytes,
wheel archive members, wheel metadata and the expected virtual-environment
layout.  Runtime files that are not part of that inventory are accepted only
when they are one of the small, deterministic virtual-environment extras.
"""

from __future__ import annotations

import base64
import csv
import io
import os
import re
import shlex
import stat
import sys
import zipfile
from collections.abc import Iterable, Mapping
from pathlib import Path, PurePosixPath
from typing import Any

from .contracts import ContractError, canonical_json_bytes, sha256_bytes, sha256_file
from .integrity_transport import unpack_installation_integrity

INSTALLATION_INTEGRITY_SCHEMA = "oel.installation-integrity.v1"
SOURCE_INVENTORY_SCHEMA = "oel.source-inventory.v1"
RUNTIME_INVENTORY_SCHEMA = "oel.runtime-inventory.v1"

_EXCLUSIONS = {
    # Generated bytecode is deliberately not an inventory exclusion.  Official
    # trees are compiled with ``pip --no-compile`` and any cache that appears
    # afterwards is an authentication failure, rather than an ignorable
    # derived artifact.  Logs remain an operational output and are excluded
    # from the signed source inventory.
    "directories": [],
    "suffixes": [],
    "globs": ["*.log"],
}
_SOURCE_EXCLUDED_SUFFIXES = frozenset(_EXCLUSIONS["suffixes"])
_BYTECODE_SUFFIXES = frozenset({".pyc", ".pyo"})


def _digest_without(value: Mapping[str, Any], field: str = "digest") -> str:
    unsigned = {str(key): item for key, item in value.items() if str(key) != field}
    return sha256_bytes(canonical_json_bytes(unsigned))


def _is_excluded(relative: PurePosixPath) -> bool:
    if any(part in _EXCLUSIONS["directories"] for part in relative.parts):
        return True
    if relative.suffix in _SOURCE_EXCLUDED_SUFFIXES:
        return True
    return any(relative.match(pattern) for pattern in _EXCLUSIONS["globs"])


def _is_bytecode_cache(relative: PurePosixPath) -> bool:
    """Return whether *relative* names Python bytecode or its cache directory."""

    return "__pycache__" in relative.parts or relative.suffix.lower() in _BYTECODE_SUFFIXES


def _reject_bytecode_cache(relative: PurePosixPath, *, label: str) -> None:
    if _is_bytecode_cache(relative):
        raise ContractError(
            f"{label} contains generated bytecode cache {relative}; "
            "official OEL trees must be installed with --no-compile and contain no unsigned bytecode."
        )


def _safe_relative(path: str | Path, *, label: str) -> PurePosixPath:
    text = str(path).replace("\\", "/")
    relative = PurePosixPath(text)
    if not text or not relative.parts or relative.is_absolute() or ".." in relative.parts or ":" in relative.parts[0]:
        raise ContractError(f"{label} contains an unsafe relative path: {path!r}")
    return relative


def _is_executable(path: Path) -> bool:
    """Return the portable executable-bit identity used by signed rows."""

    return bool(path.stat().st_mode & (stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH))


def _file_row(path: Path, relative: PurePosixPath) -> dict[str, Any]:
    if path.is_symlink() or not path.is_file():
        raise ContractError(f"Signed inventories may contain regular files only: {path}")
    return {
        "path": relative.as_posix(),
        "bytes": path.stat().st_size,
        "sha256": sha256_file(path),
        "executable": _is_executable(path),
    }


def _inventory_digest(value: Mapping[str, Any]) -> str:
    return _digest_without(value)


def build_source_inventory(root: str | Path, *, files: Iterable[str | Path] | None = None) -> dict[str, Any]:
    """Return a deterministic inventory of the exact source files shipped."""

    raw_base = Path(root).expanduser()
    if raw_base.is_symlink():
        raise ContractError(f"Source inventory root may not be a symbolic link: {raw_base}")
    base = raw_base.resolve()
    if not base.is_dir():
        raise ContractError(f"Source inventory root is not a directory: {base}")
    if files is None:
        for path in base.rglob("*"):
            relative = PurePosixPath(path.relative_to(base).as_posix())
            _reject_bytecode_cache(relative, label="Source inventory root")
        candidates = sorted(base.rglob("*"), key=lambda item: item.relative_to(base).as_posix())
    else:
        candidates = [base / Path(item) for item in files]
    rows: list[dict[str, Any]] = []
    for path in candidates:
        relative = PurePosixPath(path.relative_to(base).as_posix())
        _reject_bytecode_cache(relative, label="Signed source inventory")
        if _is_excluded(relative):
            continue
        if path.is_symlink():
            raise ContractError(f"Signed source inventory may not contain symbolic links: {path}")
        if path.is_dir():
            continue
        if not path.is_file():
            raise ContractError(f"Signed source inventory contains a non-regular path: {path}")
        rows.append(_file_row(path, relative))
    if not rows:
        raise ContractError("Signed source inventory must contain at least one file.")
    payload: dict[str, Any] = {
        "schema_version": SOURCE_INVENTORY_SCHEMA,
        "exclusions": _EXCLUSIONS,
        "files": rows,
    }
    payload["digest"] = _inventory_digest(payload)
    return payload


def _zip_member_executable(info: zipfile.ZipInfo) -> bool:
    mode = (info.external_attr >> 16) & 0xFFFF
    return bool(mode & (stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH))


def _script_first_line(data: bytes) -> tuple[bytes, bytes] | None:
    """Return a script's first line without its terminator and the terminator."""

    if not data.startswith(b"#!"):
        return None
    first = data.splitlines(keepends=True)[0] if data.splitlines(keepends=True) else data
    if first.endswith(b"\r\n"):
        return first[:-2], b"\r\n"
    if first.endswith(b"\n"):
        return first[:-1], b"\n"
    return first, b""


def _distlib_shell_trampoline(data: bytes) -> tuple[Path, bytes, bytes] | None:
    """Parse the exact distlib POSIX wrapper used for interpreters with spaces.

    pip/distlib emits this three-line shell prefix when the Python executable
    path cannot be represented as a kernel shebang.  Only this fixed prefix is
    accepted; arbitrary shell text remains part of the signed script body and
    is rejected unless it matches the signed normalized bytes.
    """

    lines = data.splitlines(keepends=True)
    if len(lines) < 3 or lines[0].rstrip(b"\r\n") != b"#!/bin/sh":
        return None
    second = lines[1].rstrip(b"\r\n")
    third = lines[2].rstrip(b"\r\n")
    match = re.fullmatch(
        rb"'''exec'[ \t]+(?P<quote>['\"])(?P<path>.+?)(?P=quote)[ \t]+\"\$0\"[ \t]+\"\$@\"[ \t]*",
        second,
    )
    if match is None:
        match = re.fullmatch(
            rb"'''exec'[ \t]+(?P<path>[^ \t\r\n'\";|&<>]+)[ \t]+\"\$0\"[ \t]+\"\$@\"[ \t]*",
            second,
        )
    if match is None or third != b"' '''":
        return None
    try:
        target = Path(os.fsdecode(match.group("path"))).expanduser()
    except (OSError, UnicodeError, ValueError):
        return None
    if not target.is_absolute():
        return None
    newline = b"\r\n" if lines[0].endswith(b"\r\n") else b"\n"
    return target, b"#!python" + newline + b"".join(lines[3:]), newline


def _interpreter_path_from_shebang(data: bytes) -> Path | None:
    first = _script_first_line(data)
    if first is None:
        return None
    raw = first[0][2:].strip()
    if not raw:
        return None
    try:
        return Path(os.fsdecode(raw)).expanduser()
    except (OSError, ValueError):
        return None


def _normalized_script_bytes(data: bytes, *, interpreter: str | Path | None = None) -> bytes:
    """Normalize only the exact ``#!python`` placeholder that pip rewrites.

    The wheel identity deliberately preserves every other shebang.  During
    installed-runtime verification, a permitted absolute interpreter path is
    normalized to the same placeholder only after the caller has separately
    checked that it resolves to the operator-owned provider.
    """

    first = _script_first_line(data)
    if first is None:
        return data
    line, newline = first
    permitted = line == b"#!python"
    if interpreter is not None:
        trampoline = _distlib_shell_trampoline(data)
        if trampoline is not None:
            shebang, normalized, _trampoline_newline = trampoline
            try:
                permitted = shebang.resolve(strict=False) == Path(interpreter).expanduser().resolve(strict=False)
            except OSError:
                permitted = False
            if permitted:
                return normalized
        else:
            shebang = _interpreter_path_from_shebang(data)
            if shebang is not None:
                try:
                    permitted = shebang.resolve(strict=False) == Path(interpreter).expanduser().resolve(strict=False)
                except OSError:
                    permitted = False
    if not permitted:
        return data
    lines = data.splitlines(keepends=True)
    return b"#!python" + newline + b"".join(lines[1:])


def _wheel_install_path(member: PurePosixPath) -> str:
    parts = member.parts
    # Wheel data directories are named ``<distribution>.data/<category>``.
    if len(parts) >= 3 and parts[0].endswith(".data"):
        category = parts[1]
        suffix = "/".join(parts[2:])
        if category in {"purelib", "platlib"}:
            return f"site-packages/{suffix}"
        if category == "scripts":
            return f"scripts/{suffix}"
        if category == "data":
            return f"runtime-data/{suffix}"
        if category == "headers":
            distribution = parts[0][:-5].rsplit("-", 1)[0]
            if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*", distribution):
                raise ContractError("Wheel headers have an invalid distribution directory.")
            python_tag = f"python{sys.version_info.major}.{sys.version_info.minor}"
            return f"runtime-data/include/site/{python_tag}/{distribution}/{suffix}"
    return f"site-packages/{member.as_posix()}"


def build_wheel_inventory(path: str | Path) -> dict[str, Any]:
    """Record wheel bytes, metadata, RECORD and install-layout mappings."""

    wheel = Path(path).expanduser().resolve()
    if wheel.is_symlink() or not wheel.is_file() or not zipfile.is_zipfile(wheel):
        raise ContractError(f"Wheel inventory requires a regular ZIP wheel: {wheel}")
    rows: list[dict[str, Any]] = []
    names: set[str] = set()
    dist_info: set[str] = set()
    with zipfile.ZipFile(wheel) as archive:
        if archive.testzip() is not None:
            raise ContractError(f"Wheel archive failed ZIP integrity validation: {wheel}")
        for info in archive.infolist():
            relative = _safe_relative(info.filename, label="wheel member")
            _reject_bytecode_cache(relative, label="Wheel archive")
            if info.filename.endswith("/"):
                continue
            if relative.as_posix() in names:
                raise ContractError(f"Wheel archive contains duplicate member: {relative}")
            names.add(relative.as_posix())
            mode = (info.external_attr >> 16) & 0xFFFF
            file_type = stat.S_IFMT(mode)
            if stat.S_ISLNK(mode) or (file_type and not stat.S_ISREG(mode)):
                raise ContractError(f"Wheel archive contains a symbolic or special member: {relative}")
            if ".dist-info/" in relative.as_posix():
                root = relative.as_posix().split("/", 1)[0]
                if root.endswith(".dist-info"):
                    dist_info.add(root)
            data = archive.read(info)
            install_path = _wheel_install_path(relative)
            row = {
                "path": relative.as_posix(),
                "install_path": install_path,
                "bytes": len(data),
                "sha256": sha256_bytes(data),
                "executable": _zip_member_executable(info),
            }
            if install_path.startswith("scripts/"):
                normalized = _normalized_script_bytes(data)
                row["installed_bytes"] = len(normalized)
                row["installed_sha256"] = sha256_bytes(normalized)
                row["pip_placeholder_shebang"] = bool(
                    (_script_first_line(data) or (b"", b""))[0] == b"#!python"
                )
            rows.append(
                row
            )
    if len(dist_info) != 1:
        raise ContractError(f"Wheel must contain exactly one dist-info directory: {wheel}")
    metadata_root = next(iter(dist_info))
    required = {f"{metadata_root}/METADATA", f"{metadata_root}/WHEEL", f"{metadata_root}/RECORD"}
    if not required.issubset(names):
        raise ContractError(f"Wheel is missing METADATA, WHEEL or RECORD: {wheel}")
    generated_scripts: list[dict[str, Any]] = []
    entry_points_path = f"{metadata_root}/entry_points.txt"
    with zipfile.ZipFile(wheel) as archive:
        if entry_points_path in archive.namelist():
            try:
                section = ""
                for raw_line in archive.read(entry_points_path).decode("utf-8").splitlines():
                    line = raw_line.strip()
                    if not line or line.startswith("#"):
                        continue
                    if line.startswith("[") and line.endswith("]"):
                        section = line[1:-1].strip().lower()
                        continue
                    if section not in {"console_scripts", "gui_scripts"} or "=" not in line:
                        continue
                    name, target = (part.strip() for part in line.split("=", 1))
                    if re.fullmatch(r"[A-Za-z0-9_.-]+", name) and target:
                        generated_scripts.append(
                            {
                                "name": name,
                                "install_path": f"scripts/{name}",
                                "entry_point": target,
                            }
                        )
            except UnicodeError as exc:
                raise ContractError(f"Wheel entry_points.txt is not UTF-8: {wheel}") from exc
    payload: dict[str, Any] = {
        "name": wheel.name,
        "bytes": wheel.stat().st_size,
        "sha256": sha256_file(wheel),
        "dist_info": metadata_root,
        "record": f"{metadata_root}/RECORD",
        "files": sorted(rows, key=lambda row: str(row["path"])),
        "scripts": sorted(
            [row for row in rows if str(row["install_path"]).startswith("scripts/")],
            key=lambda row: str(row["install_path"]),
        ),
        "generated_scripts": sorted(generated_scripts, key=lambda row: str(row["install_path"])),
    }
    return payload


def _runtime_layout_extras(
    runtime_root: Path | None,
    *,
    expected_interpreter: str,
    provider: Mapping[str, Any],
) -> list[dict[str, Any]]:
    """Describe the small venv surface outside signed wheel members.

    Activation and pip convenience scripts are removed by the installer and
    are never accepted as an unsigned filename allowlist.  The remaining
    aliases are explicitly bound to the external provider and ``pyvenv.cfg``
    has a semantic contract rather than a mutable content exemption.
    """

    extras: list[dict[str, Any]] = [
        {
            "path": "pyvenv.cfg",
            "kind": "venv-config",
            "include_system_site_packages": False,
            "provider_boundary": str(provider.get("boundary", "external-interpreter")),
        }
    ]
    if runtime_root is None:
        parent = PurePosixPath(expected_interpreter).parent
        names = [PurePosixPath(expected_interpreter).name]
        if os.name != "nt":
            names.extend(["python3", f"python{sys.version_info.major}.{sys.version_info.minor}"])
        aliases = [parent / name for name in names]
    else:
        interpreter_parent = PurePosixPath(expected_interpreter).parent.as_posix()
        directory = runtime_root / Path(interpreter_parent)
        aliases = []
        if directory.is_dir():
            for candidate in sorted(directory.iterdir(), key=lambda item: item.name):
                # CPython 3.14's venv also emits the Unicode 𝜋thon alias.
                # Record it in the signed layout so the ordinary provider
                # target checks apply; it is never an unsigned exemption.
                if (
                    candidate.name.lower().startswith("python") or candidate.name == "𝜋thon"
                ) and candidate.is_file():
                    aliases.append(PurePosixPath(candidate.relative_to(runtime_root).as_posix()))
    seen: set[str] = set()
    for alias in aliases:
        path = alias.as_posix()
        if path in seen:
            continue
        seen.add(path)
        extras.append({"path": path, "kind": "provider-alias", "provider_boundary": str(provider.get("boundary", "external-interpreter"))})
    if os.name != "nt" and (runtime_root is None or (runtime_root / "lib64").exists()):
        extras.append({"path": "lib64", "kind": "lib-alias", "target": "lib"})
    return extras


def build_runtime_inventory(
    wheels: Iterable[str | Path],
    *,
    interpreter: str | None = None,
    provider: Mapping[str, Any] | None = None,
    profile: str = "core",
    runtime_root: str | Path | None = None,
) -> dict[str, Any]:
    wheel_rows = [build_wheel_inventory(path) for path in wheels]
    wheel_rows.sort(key=lambda row: str(row["name"]))
    if len({str(row["name"]) for row in wheel_rows}) != len(wheel_rows):
        raise ContractError("Runtime inventory contains duplicate wheel names.")
    expected_interpreter = interpreter or ("Scripts/python.exe" if os.name == "nt" else "bin/python")
    provider_row = dict(provider or {"boundary": "external-interpreter", "trust": "operator-owned"})
    runtime_path = Path(runtime_root).expanduser() if runtime_root is not None else None
    if runtime_path is not None and (runtime_path.is_symlink() or not runtime_path.is_dir()):
        raise ContractError("Runtime inventory source must be a regular directory.")
    extras = _runtime_layout_extras(
        runtime_path,
        expected_interpreter=expected_interpreter,
        provider=provider_row,
    )
    if runtime_path is not None:
        # Bind generated entry-point wrappers to their installed bytes.  The
        # archive member is only the recipe; pip creates a distinct wrapper.
        script_rows = {
            str(script.get("install_path")): script
            for wheel in wheel_rows
            for script in list(wheel.get("generated_scripts", []) or [])
        }
        for symbolic, script in script_rows.items():
            try:
                target = _runtime_target(runtime_path, symbolic, _runtime_site_packages(runtime_path) or runtime_path)
            except ContractError:
                continue
            if target.is_file() and not target.is_symlink():
                data = target.read_bytes()
                normalized = _normalized_script_bytes(data, interpreter=runtime_path / expected_interpreter)
                script["installed_bytes"] = len(normalized)
                script["installed_sha256"] = sha256_bytes(normalized)
                script["executable"] = _is_executable(target)
    interpreter_file: dict[str, Any] | None = None
    if runtime_path is not None:
        interpreter_target = runtime_path / Path(expected_interpreter)
        if interpreter_target.is_file() and not interpreter_target.is_symlink():
            interpreter_file = {
                "bytes": interpreter_target.stat().st_size,
                "sha256": sha256_file(interpreter_target),
                "executable": _is_executable(interpreter_target),
            }
    payload: dict[str, Any] = {
        "schema_version": RUNTIME_INVENTORY_SCHEMA,
        "profile": str(profile),
        "wheels": wheel_rows,
        "layout": {
            "interpreter": expected_interpreter,
            "provider": provider_row,
            "extras": extras,
            **({"interpreter_file": interpreter_file} if interpreter_file is not None else {}),
        },
    }
    payload["digest"] = _inventory_digest(payload)
    return payload


def build_installation_integrity(
    source_root: str | Path,
    wheels: Iterable[str | Path] = (),
    *,
    interpreter: str | None = None,
    provider: Mapping[str, Any] | None = None,
    source_files: Iterable[str | Path] | None = None,
    profile: str = "core",
    profile_wheels: Mapping[str, Iterable[str | Path]] | None = None,
    runtime_profiles: Mapping[str, Mapping[str, Any]] | None = None,
) -> dict[str, Any]:
    source = build_source_inventory(source_root, files=source_files)
    if runtime_profiles is not None:
        profile_rows = {str(name): dict(row) for name, row in runtime_profiles.items()}
        if not profile_rows:
            raise ContractError("Signed installation integrity must contain a profile runtime inventory.")
        runtime = profile_rows.get(profile)
        if runtime is None:
            raise ContractError(f"Signed installation integrity has no runtime inventory for profile {profile!r}.")
    else:
        selected_wheels = profile_wheels or {profile: wheels}
        profile_rows = {
            str(name): build_runtime_inventory(
                items,
                interpreter=interpreter,
                provider=provider,
                profile=str(name),
            )
            for name, items in selected_wheels.items()
        }
        runtime = profile_rows.get(profile)
        if runtime is None:
            raise ContractError(f"Signed installation integrity has no runtime inventory for profile {profile!r}.")
    payload: dict[str, Any] = {
        "schema_version": INSTALLATION_INTEGRITY_SCHEMA,
        "profile": str(profile),
        "source": source,
        "runtime": runtime,
        "runtime_profiles": profile_rows,
    }
    payload["digest"] = _inventory_digest(payload)
    return payload


def validate_installation_integrity(value: Any) -> dict[str, Any]:
    try:
        value = unpack_installation_integrity(value)
    except ValueError as exc:
        raise ContractError(str(exc)) from exc
    if not isinstance(value, Mapping) or value.get("schema_version") != INSTALLATION_INTEGRITY_SCHEMA:
        raise ContractError(f"Signed installation integrity must use {INSTALLATION_INTEGRITY_SCHEMA}.")
    source = value.get("source")
    runtime = value.get("runtime")
    runtime_profiles = value.get("runtime_profiles")
    selected_profile = value.get("profile")
    if not isinstance(selected_profile, str) or not selected_profile:
        raise ContractError("Signed installation integrity has no authenticated profile selector.")
    if not isinstance(source, Mapping) or source.get("schema_version") != SOURCE_INVENTORY_SCHEMA:
        raise ContractError("Signed installation integrity has no valid source inventory.")
    if not isinstance(runtime, Mapping) or runtime.get("schema_version") != RUNTIME_INVENTORY_SCHEMA:
        raise ContractError("Signed installation integrity has no valid runtime inventory.")
    if not isinstance(runtime_profiles, Mapping) or not runtime_profiles:
        raise ContractError("Signed installation integrity has no profile-specific runtime inventories.")
    for inventory, label in ((source, "source"), (runtime, "runtime"), (value, "installation")):
        digest = inventory.get("digest")
        if not isinstance(digest, str) or digest != _inventory_digest(inventory):
            raise ContractError(f"Signed {label} inventory digest is invalid.")
    for profile, profile_inventory in runtime_profiles.items():
        if not isinstance(profile, str) or not profile or not isinstance(profile_inventory, Mapping):
            raise ContractError("Signed profile runtime inventories are malformed.")
        if profile_inventory.get("profile") != profile:
            raise ContractError(f"Signed runtime inventory profile binding is invalid for {profile!r}.")
        _validate_runtime_inventory(profile_inventory)
    if runtime_profiles.get(selected_profile) != runtime or runtime.get("profile") != selected_profile:
        raise ContractError("Signed runtime inventory is not the selected profile inventory.")
    _validate_source_inventory(source)
    wheel_rows = runtime.get("wheels")
    if not isinstance(wheel_rows, list):
        raise ContractError("Signed runtime inventory wheels must be a list.")
    seen_wheels: set[str] = set()
    for wheel in wheel_rows:
        if not isinstance(wheel, Mapping):
            raise ContractError("Signed runtime inventory contains a malformed wheel.")
        name = str(wheel.get("name", ""))
        if not name or Path(name).name != name or name in seen_wheels:
            raise ContractError(f"Signed runtime inventory has an invalid or duplicate wheel name: {name!r}")
        seen_wheels.add(name)
        _validate_hash_row(wheel, label=f"runtime wheel {name}")
        members = wheel.get("files")
        if not isinstance(members, list) or not members:
            raise ContractError(f"Signed runtime wheel {name} has no members.")
        member_paths: set[str] = set()
        for member in members:
            if not isinstance(member, Mapping):
                raise ContractError(f"Signed runtime wheel {name} has a malformed member.")
            member_path = _safe_relative(member.get("path", ""), label=f"runtime wheel {name}")
            _reject_bytecode_cache(member_path, label=f"Signed runtime wheel {name}")
            if member_path.as_posix() in member_paths:
                raise ContractError(f"Signed runtime wheel {name} has duplicate member: {member_path}")
            member_paths.add(member_path.as_posix())
            _validate_hash_row(member, label=f"runtime wheel {name}")
            _safe_relative(member.get("install_path", ""), label=f"runtime wheel {name} install path")
        generated_scripts = wheel.get("generated_scripts", [])
        if not isinstance(generated_scripts, list):
            raise ContractError(f"Signed runtime wheel {name} generated scripts are malformed.")
        for script in generated_scripts:
            if not isinstance(script, Mapping) or not re.fullmatch(
                r"[A-Za-z0-9_.-]+", str(script.get("name", ""))
            ):
                raise ContractError(f"Signed runtime wheel {name} generated script is malformed.")
            _safe_relative(script.get("install_path", ""), label=f"runtime wheel {name} script install path")
    layout = runtime.get("layout")
    if not isinstance(layout, Mapping) or not isinstance(layout.get("interpreter"), str):
        raise ContractError("Signed runtime inventory has no interpreter layout.")
    _safe_relative(layout["interpreter"], label="runtime interpreter")
    return dict(value)


def _validate_source_inventory(source: Mapping[str, Any]) -> None:
    if source.get("exclusions") != _EXCLUSIONS:
        raise ContractError("Signed source inventory exclusions are not the deterministic OEL allowlist.")
    files = source.get("files")
    if not isinstance(files, list) or not files:
        raise ContractError("Signed source inventory must contain files.")
    seen: set[str] = set()
    for row in files:
        if not isinstance(row, Mapping):
            raise ContractError("Signed source inventory contains a malformed row.")
        relative = _safe_relative(row.get("path", ""), label="source inventory")
        _reject_bytecode_cache(relative, label="Signed source inventory")
        if relative.as_posix() in seen:
            raise ContractError(f"Signed source inventory contains duplicate path: {relative}")
        seen.add(relative.as_posix())
        _validate_hash_row(row, label="source inventory")


def _validate_hash_row(row: Mapping[str, Any], *, label: str) -> None:
    size = row.get("bytes")
    digest = row.get("sha256")
    if isinstance(size, bool) or not isinstance(size, int) or size < 0:
        raise ContractError(f"{label} byte count is invalid.")
    if not isinstance(digest, str) or len(digest) != 64 or any(char not in "0123456789abcdef" for char in digest):
        raise ContractError(f"{label} SHA-256 is invalid.")


def verify_source_inventory(root: str | Path, inventory: Mapping[str, Any]) -> list[str]:
    """Return source mismatches; the caller decides official disposition."""

    if not isinstance(inventory, Mapping) or inventory.get("schema_version") != SOURCE_INVENTORY_SCHEMA:
        return ["signed source inventory schema is invalid"]
    try:
        if inventory.get("digest") != _inventory_digest(inventory):
            return ["signed source inventory digest is invalid"]
        _validate_source_inventory(inventory)
    except ContractError as exc:
        return [str(exc)]
    expected = {str(row["path"]): dict(row) for row in list(inventory.get("files", []) or [])}
    raw_base = Path(root).expanduser()
    if raw_base.is_symlink():
        return ["installed source directory may not be a symbolic link"]
    base = raw_base.resolve()
    actual: dict[str, dict[str, Any]] = {}
    issues: list[str] = []
    if not base.is_dir():
        return ["installed source directory missing"]
    for path in sorted(base.rglob("*"), key=lambda item: item.relative_to(base).as_posix()):
        relative = PurePosixPath(path.relative_to(base).as_posix())
        if _is_bytecode_cache(relative):
            issues.append(f"unsigned bytecode cache present in source: {relative}")
            continue
        if _is_excluded(relative):
            continue
        if path.is_symlink():
            actual[relative.as_posix()] = {"error": "symbolic link"}
        elif path.is_file():
            actual[relative.as_posix()] = _file_row(path, relative)
        elif not path.is_dir():
            actual[relative.as_posix()] = {"error": "non-regular path"}
    for path in sorted(set(expected) | set(actual)):
        if path not in expected:
            issues.append(f"unexpected source file: {path}")
        elif path not in actual:
            issues.append(f"missing source file: {path}")
        elif actual[path] != expected[path]:
            issues.append(f"source inventory mismatch: {path}")
    return issues


def _runtime_site_packages(root: Path) -> Path | None:
    candidates = sorted((root / "lib").glob("python*/site-packages"))
    candidates.extend([root / "Lib" / "site-packages"])
    return next((path for path in candidates if path.is_dir() and not path.is_symlink()), None)


def _lexical_symlink(path: Path, *, stop: Path) -> Path | None:
    """Return the first symlink on a lexical path between *path* and *stop*."""

    current = path.absolute()
    stop_absolute = stop.absolute()
    while True:
        if current.is_symlink():
            return current
        if current == stop_absolute:
            return None
        try:
            current.relative_to(stop_absolute)
        except ValueError:
            return current if current.is_symlink() else None
        parent = current.parent
        if parent == current:
            return None
        current = parent


def _runtime_path_issue(path: Path, *, root: Path) -> str | None:
    try:
        path.absolute().relative_to(root.absolute())
    except ValueError:
        return f"managed runtime path escapes its lexical root: {path}"
    link = _lexical_symlink(path, stop=root)
    if link is not None:
        return f"managed runtime path contains an unexpected symbolic link: {link}"
    return None


def _runtime_target(root: Path, symbolic: str, site_packages: Path) -> Path:
    if symbolic.startswith("site-packages/"):
        return site_packages / PurePosixPath(symbolic).relative_to("site-packages")
    if symbolic.startswith("scripts/"):
        return root / ("Scripts" if os.name == "nt" else "bin") / PurePosixPath(symbolic).relative_to("scripts")
    if symbolic.startswith("runtime-data/"):
        return root / PurePosixPath(symbolic).relative_to("runtime-data")
    raise ContractError(f"Unknown signed runtime install path: {symbolic}")


def _rebind_runtime_scripts(root: Path, inventory: Mapping[str, Any], destination: Path) -> None:
    """Relocate only authenticated interpreter placeholders before publication.

    The caller verifies the staged runtime first and the published runtime
    afterwards. Script bodies retain their signed normalized bytes; installed
    RECORD hashes change only for the rewritten interpreter wrappers.
    """

    site = _runtime_site_packages(root)
    if site is None:
        raise ContractError("Cannot relocate scripts without managed site-packages.")
    interpreter = root / str(inventory["layout"]["interpreter"])
    future = destination / str(inventory["layout"]["interpreter"])
    expected: dict[str, Mapping[str, Any]] = {}
    for wheel in inventory["wheels"]:
        for row in wheel["files"]:
            if str(row["install_path"]).startswith("scripts/") and row.get("pip_placeholder_shebang"):
                expected[str(row["install_path"])] = row
        expected.update({str(row["install_path"]): row for row in wheel.get("generated_scripts", [])})
    if expected and os.name == "nt":
        raise ContractError("Signed Windows runtime script relocation requires separate qualification.")
    changed: dict[Path, bytes] = {}
    record_aliases: dict[str, Path] = {}
    for symbolic, row in expected.items():
        target = _runtime_target(root, symbolic, site)
        if target.is_symlink() or not target.is_file():
            raise ContractError(f"Cannot relocate missing or linked runtime script: {symbolic}")
        normalized = _normalized_script_bytes(target.read_bytes(), interpreter=interpreter)
        if len(normalized) != row["installed_bytes"] or sha256_bytes(normalized) != row["installed_sha256"]:
            raise ContractError(f"Cannot relocate unauthenticated runtime script: {symbolic}")
        first, *body = normalized.splitlines(keepends=True)
        if first not in {b"#!python\n", b"#!python\r\n"}:
            raise ContractError(f"Cannot relocate a script without an authenticated interpreter placeholder: {symbolic}")
        newline = b"\r\n" if first.endswith(b"\r\n") else b"\n"
        data = (
            b"#!/bin/sh" + newline + b"'''exec' " + os.fsencode(shlex.quote(str(future)))
            + b' "$0" "$@"' + newline + b"' '''" + newline + b"".join(body)
        )
        if _normalized_script_bytes(data, interpreter=future) != normalized:
            raise ContractError(f"Relocated runtime script changed its signed body: {symbolic}")
        target.write_bytes(data)
        changed[target] = data
        name = symbolic.removeprefix("scripts/")
        for alias in (symbolic, "bin/" + name, "Scripts/" + name, str(row.get("path", ""))):
            if alias:
                record_aliases[alias] = target
    recorded: set[Path] = set()
    for wheel in inventory["wheels"]:
        record = _runtime_target(root, "site-packages/" + str(wheel["record"]), site)
        rows = list(csv.reader(io.StringIO(record.read_text(encoding="utf-8"))))
        modified = False
        for row in rows:
            if len(row) != 3:
                raise ContractError("Cannot relocate scripts with a malformed runtime RECORD.")
            raw_path = row[0].replace("\\", "/")
            target = record_aliases.get(raw_path, Path(os.path.abspath(site / raw_path)))
            if target in changed:
                data = changed[target]
                digest = base64.urlsafe_b64encode(bytes.fromhex(sha256_bytes(data))).decode("ascii").rstrip("=")
                row[1:] = ["sha256=" + digest, str(len(data))]
                recorded.add(target)
                modified = True
        if modified:
            stream = io.StringIO()
            csv.writer(stream, lineterminator="\n").writerows(rows)
            record.write_text(stream.getvalue(), encoding="utf-8")
    if set(changed) != recorded:
        raise ContractError("Relocated runtime scripts are missing from installed RECORD files.")


def _standard_runtime_extra(root: Path, relative: PurePosixPath) -> bool:
    # Kept as a compatibility seam for callers that import the old helper.
    # Verification now accepts only entries present in the signed layout
    # extras and the one explicit lib64 alias.
    return relative.as_posix() == "lib64"


def _read_runtime_files(root: Path) -> dict[str, Path]:
    files: dict[str, Path] = {}
    for path in sorted(root.rglob("*"), key=lambda item: item.relative_to(root).as_posix()):
        relative = PurePosixPath(path.relative_to(root).as_posix())
        if path.is_symlink():
            files[relative.as_posix()] = path
        elif path.is_file():
            files[relative.as_posix()] = path
        elif not path.is_dir():
            files[relative.as_posix()] = path
    return files


def _shebang_matches(data: bytes, interpreter: str | Path | None) -> bool:
    if interpreter is None:
        return False
    trampoline = _distlib_shell_trampoline(data)
    if trampoline is not None:
        candidate = trampoline[0]
    else:
        candidate = _interpreter_path_from_shebang(data)
        if candidate is None:
            return False
    try:
        return candidate.resolve(strict=False) == Path(interpreter).expanduser().resolve(strict=False)
    except OSError:
        return False


def _verify_venv_config(path: Path, *, root: Path, provider_target: Path | None = None) -> list[str]:
    issues: list[str] = []
    try:
        values: dict[str, str] = {}
        for raw_line in path.read_text(encoding="utf-8", errors="strict").splitlines():
            line = raw_line.strip()
            if not line:
                continue
            if "=" not in line:
                issues.append("managed runtime pyvenv.cfg contains a malformed line")
                continue
            key, value = (item.strip() for item in line.split("=", 1))
            if key in values:
                issues.append(f"managed runtime pyvenv.cfg repeats key: {key}")
            values[key] = value
    except (OSError, UnicodeError) as exc:
        return [f"managed runtime pyvenv.cfg is unreadable: {exc}"]
    if values.get("include-system-site-packages", "").lower() != "false":
        issues.append("managed runtime pyvenv.cfg must disable system site packages")
    home = values.get("home", "")
    if not home or not Path(home).is_absolute():
        issues.append("managed runtime pyvenv.cfg home must be an absolute operator path")
    else:
        try:
            Path(home).resolve(strict=False).relative_to(root)
        except ValueError:
            pass
        else:
            issues.append("managed runtime pyvenv.cfg home may not point inside the managed runtime")
        if provider_target is not None:
            try:
                home_path = Path(home).resolve(strict=False)
                if provider_target.resolve(strict=False).parent != home_path:
                    issues.append("managed runtime pyvenv.cfg home does not bind the external interpreter provider")
            except OSError:
                issues.append("managed runtime pyvenv.cfg home is not a usable provider boundary")
    return issues


def _verify_record(runtime_root: Path, site_packages: Path, wheel: Mapping[str, Any], expected_paths: set[str]) -> list[str]:
    record_symbolic = f"site-packages/{wheel['record']}"
    record = _runtime_target(runtime_root, record_symbolic, site_packages)
    if not record.is_file() or record.is_symlink():
        return [f"runtime RECORD missing: {wheel['name']}"]
    issues: list[str] = []
    try:
        rows = list(csv.reader(io.StringIO(record.read_text(encoding="utf-8", errors="strict"))))
    except (OSError, UnicodeError, csv.Error) as exc:
        return [f"runtime RECORD unreadable for {wheel['name']}: {exc}"]
    seen: set[str] = set()
    for row in rows:
        if len(row) != 3:
            issues.append(f"runtime RECORD row malformed for {wheel['name']}")
            continue
        raw_path, digest, size = row[:3]
        symbolic = raw_path.replace("\\", "/")
        if symbolic.startswith("/"):
            issues.append(f"runtime RECORD path escapes runtime: {raw_path}")
            continue
        if not symbolic or PurePosixPath(symbolic).is_absolute():
            issues.append(f"runtime RECORD path escapes runtime: {raw_path}")
            continue
        # pip can write generated entry points as ``bin/name`` (or
        # ``Scripts/name``) or as a path relative to the dist-info directory,
        # usually ``../../../bin/name`` on POSIX and ``../../Scripts/name`` on
        # Windows.  Accept exactly the number of parents required to reach the
        # lexical runtime root; arbitrary parent stripping would let a RECORD
        # row name an unrelated path that happens to match a signed member.
        parent_count = 0
        while symbolic.startswith("../"):
            parent_count += 1
            symbolic = symbolic[3:]
        if not symbolic or ".." in PurePosixPath(symbolic).parts:
            issues.append(f"runtime RECORD path escapes runtime: {raw_path}")
            continue
        runtime_depth = len(site_packages.relative_to(runtime_root).parts)
        if parent_count:
            parts = symbolic.split("/", 1)
            if parent_count != runtime_depth or len(parts) != 2:
                issues.append(f"runtime RECORD path has an unsupported parent mapping: {raw_path}")
                continue
            if parts[0] in {"bin", "Scripts"}:
                candidate = "scripts/" + parts[1]
            elif "runtime-data/" + symbolic in expected_paths:
                candidate = "runtime-data/" + symbolic
            else:
                issues.append(f"runtime RECORD path has an unsupported parent mapping: {raw_path}")
                continue
        else:
            # Installed RECORD uses site-packages-relative paths for ordinary
            # members and may use the wheel ``<dist>.data`` path for data
            # members.  The direct bin/Scripts form is pip's normalized entry
            # point representation.
            parts = symbolic.split("/", 2)
            if len(parts) == 3 and parts[0].endswith(".data"):
                if parts[1] not in {"purelib", "platlib", "scripts", "data", "headers"}:
                    issues.append(f"runtime RECORD path has an unsupported wheel mapping: {raw_path}")
                    continue
                symbolic = _wheel_install_path(PurePosixPath(symbolic))
            if symbolic.startswith("site-packages/") or symbolic.startswith("scripts/") or symbolic.startswith("runtime-data/"):
                candidate = symbolic
            elif symbolic.startswith("bin/") or symbolic.startswith("Scripts/"):
                candidate = "scripts/" + symbolic.split("/", 1)[1]
            else:
                candidate = "site-packages/" + symbolic
        if candidate not in expected_paths and candidate != record_symbolic:
            issues.append(f"runtime RECORD contains unexpected path: {raw_path}")
            continue
        if candidate in seen:
            issues.append(f"runtime RECORD contains duplicate path: {raw_path}")
            continue
        seen.add(candidate)
        target = _runtime_target(runtime_root, candidate, site_packages)
        if not target.is_file() or target.is_symlink():
            issues.append(f"runtime RECORD target missing: {raw_path}")
            continue
        if candidate == record_symbolic:
            if digest or size:
                issues.append(f"runtime RECORD self-row must have empty hash and size: {raw_path}")
            continue
        if not digest:
            issues.append(f"runtime RECORD hash is missing: {raw_path}")
        else:
            try:
                algorithm, encoded = digest.split("=", 1)
                if algorithm != "sha256" or not encoded:
                    raise ValueError("unsupported hash")
                import base64

                expected = base64.urlsafe_b64decode(encoded + "=" * ((4 - len(encoded) % 4) % 4)).hex()
                if expected != sha256_file(target):
                    issues.append(f"runtime RECORD hash mismatch: {raw_path}")
            except (ValueError, UnicodeError):
                issues.append(f"runtime RECORD hash is malformed: {raw_path}")
        try:
            if not size or int(size) < 0 or int(size) != target.stat().st_size:
                issues.append(f"runtime RECORD byte count mismatch: {raw_path}")
        except ValueError:
            issues.append(f"runtime RECORD byte count is malformed: {raw_path}")
    missing = (expected_paths | {record_symbolic}) - seen
    issues.extend(f"runtime RECORD omits path: {path}" for path in sorted(missing))
    return issues


def verify_runtime_inventory(
    runtime_root: str | Path,
    inventory: Mapping[str, Any],
    *,
    interpreter: str | Path | None = None,
    trusted_provider: str | Path | None = None,
) -> list[str]:
    """Return mismatches between the signed wheel inventory and a venv."""

    raw_root = Path(runtime_root).expanduser()
    if raw_root.is_symlink():
        return ["managed runtime root may not be a symbolic link"]
    # Keep the lexical managed boundary intact before resolving any expected
    # package path.  Checking only the immediate parent leaves a higher-level
    # symlink (for example ``versions``) able to redirect the whole runtime.
    for parent in raw_root.parents:
        if parent.is_symlink():
            return [f"managed runtime parent may not be a symbolic link: {parent}"]
    root = raw_root.absolute()
    if not root.is_dir():
        return ["managed runtime directory missing"]
    try:
        runtime = dict(inventory)
        # Validate runtime directly so an empty source inventory is not needed
        # by callers that only have a runtime proof.
        _validate_runtime_inventory(runtime)
    except ContractError as exc:
        return [str(exc)]
    site_packages = _runtime_site_packages(root)
    if site_packages is None:
        return ["managed runtime site-packages directory missing"]
    site_issue = _runtime_path_issue(site_packages, root=root)
    if site_issue is not None:
        return [site_issue]
    layout = dict(runtime.get("layout", {}) or {})
    signed_extras = {
        str(extra.get("path")): dict(extra)
        for extra in list(layout.get("extras", []) or [])
        if isinstance(extra, Mapping)
    }
    expected: dict[str, dict[str, Any]] = {}
    generated: dict[str, dict[str, Any]] = {}
    issues: list[str] = []
    for wheel in list(runtime.get("wheels", []) or []):
        for member in list(wheel.get("files", []) or []):
            symbolic = str(member["install_path"])
            try:
                target = _runtime_target(root, symbolic, site_packages)
            except ContractError as exc:
                issues.append(str(exc))
                continue
            relative = target.relative_to(root).as_posix()
            expected[relative] = dict(member)
            target_issue = _runtime_path_issue(target, root=root)
            if target_issue is not None:
                issues.append(target_issue)
                continue
            if not target.is_file() or target.is_symlink():
                issues.append(f"managed runtime file missing: {relative}")
                continue
            is_record = symbolic == f"site-packages/{str(wheel['record'])}"
            if not is_record and symbolic.startswith("scripts/"):
                data = target.read_bytes()
                if bool(member.get("pip_placeholder_shebang")) and not _shebang_matches(data, interpreter):
                    issues.append(f"managed runtime script interpreter mismatch: {relative}")
                normalized = _normalized_script_bytes(
                    data,
                    interpreter=interpreter if bool(member.get("pip_placeholder_shebang")) else None,
                )
                installed_size = int(member["installed_bytes"])
                installed_digest = str(member["installed_sha256"])
                if len(normalized) != installed_size or sha256_bytes(normalized) != installed_digest:
                    issues.append(f"managed runtime script mismatch: {relative}")
            elif not is_record and (target.stat().st_size != int(member["bytes"]) or sha256_file(target) != member["sha256"]):
                issues.append(f"managed runtime file mismatch: {relative}")
            if not is_record and _is_executable(target) != bool(member.get("executable")):
                issues.append(f"managed runtime executable bit mismatch: {relative}")
        for script in list(wheel.get("generated_scripts", []) or []):
            symbolic = str(script.get("install_path", ""))
            try:
                target = _runtime_target(root, symbolic, site_packages)
            except ContractError as exc:
                issues.append(str(exc))
                continue
            relative = target.relative_to(root).as_posix()
            generated[relative] = dict(script)
            target_issue = _runtime_path_issue(target, root=root)
            if target_issue is not None:
                issues.append(target_issue)
                continue
            if not target.is_file() or target.is_symlink():
                issues.append(f"generated runtime script missing: {relative}")
                continue
            if _is_executable(target) != bool(script.get("executable")):
                issues.append(f"generated runtime script executable bit mismatch: {relative}")
                continue
            try:
                data = target.read_bytes()
                first_line = data.splitlines()[0].decode("utf-8", errors="strict")
            except (OSError, UnicodeError, IndexError) as exc:
                issues.append(f"generated runtime script is unreadable: {relative}: {exc}")
                continue
            if not first_line.startswith("#!") or not _shebang_matches(data, interpreter):
                issues.append(f"generated runtime script has no interpreter binding: {relative}")
            normalized = _normalized_script_bytes(data, interpreter=interpreter)
            if len(normalized) != int(script["installed_bytes"]) or sha256_bytes(normalized) != str(script["installed_sha256"]):
                issues.append(f"generated runtime script content mismatch: {relative}")
        record_paths = {str(row["install_path"]) for row in wheel["files"]}
        record_paths.update(str(row.get("install_path", "")) for row in wheel.get("generated_scripts", []))
        issues.extend(_verify_record(root, site_packages, wheel, record_paths))
    interpreter_path = root / str(layout.get("interpreter", ""))
    interpreter_issue = _runtime_path_issue(interpreter_path.parent, root=root)
    if interpreter_issue is not None:
        issues.append(interpreter_issue)
    provider_target: Path | None = None
    if not interpreter_path.exists() and not interpreter_path.is_symlink():
        issues.append("managed runtime interpreter missing")
    elif interpreter_path.is_symlink():
        try:
            provider = interpreter_path.resolve(strict=True)
        except OSError:
            issues.append("managed runtime interpreter provider is missing")
        else:
            provider_target = provider
            if not provider.is_file() or provider == interpreter_path:
                issues.append("managed runtime interpreter provider is not a regular external file")
            try:
                provider.relative_to(root)
            except ValueError:
                pass
            else:
                issues.append("managed runtime interpreter provider must be outside the managed runtime")
            if trusted_provider is not None:
                try:
                    trusted = Path(trusted_provider).expanduser().resolve(strict=True)
                except OSError:
                    issues.append("trusted external interpreter provider is unavailable")
                else:
                    if provider != trusted:
                        issues.append("managed runtime interpreter provider does not match the trusted external verifier provider")
    elif not interpreter_path.is_file():
        issues.append("managed runtime interpreter is not a regular file")
    else:
        interpreter_file = layout.get("interpreter_file")
        if not isinstance(interpreter_file, Mapping):
            issues.append("managed runtime interpreter lacks a signed file identity")
        elif (
            sha256_file(interpreter_path) != interpreter_file.get("sha256")
            or interpreter_path.stat().st_size != interpreter_file.get("bytes")
            or _is_executable(interpreter_path) != bool(interpreter_file.get("executable"))
        ):
            issues.append("managed runtime interpreter file identity mismatch")
    actual = _read_runtime_files(root)
    expected_names = set(expected) | set(generated)
    expected_names.add(PurePosixPath(str(layout.get("interpreter", ""))).as_posix())
    expected_names.update(signed_extras)
    # Every signed layout extra is part of the authenticated runtime contract;
    # accepting only extras that happen to exist would turn a missing provider
    # alias or venv configuration into a silent downgrade of that contract.
    for name in sorted(signed_extras):
        extra_path = root / PurePosixPath(name)
        # The extra itself may be the one intentional provider/lib symlink;
        # only its parent chain is required to remain lexical and managed.
        extra_issue = _runtime_path_issue(extra_path.parent, root=root)
        if extra_issue is not None:
            issues.append(extra_issue)
        elif not extra_path.exists() and not extra_path.is_symlink():
            issues.append(f"signed managed runtime layout extra missing: {name}")
    # ``_read_runtime_files`` intentionally omits directories, so scan the
    # complete runtime tree first to reject an empty __pycache__ as well as
    # forged .pyc/.pyo files.  Preventing writes does not prevent Python from
    # importing a pre-existing cache; no cache is trusted by the official
    # runtime policy.
    for path in sorted(root.rglob("*"), key=lambda item: item.relative_to(root).as_posix()):
        relative = PurePosixPath(path.relative_to(root).as_posix())
        if _is_bytecode_cache(relative):
            issues.append(f"unsigned bytecode cache present in runtime: {relative}")
        if path.is_symlink() and relative.as_posix() not in signed_extras and relative.as_posix() != PurePosixPath(str(layout.get("interpreter", ""))).as_posix():
            issues.append(f"unexpected symbolic link in managed runtime: {relative}")
    for name, path in actual.items():
        relative = PurePosixPath(name)
        extra = signed_extras.get(name)
        if extra is not None:
            kind = str(extra.get("kind", ""))
            if kind == "venv-config":
                if path.is_symlink():
                    issues.append(f"managed runtime venv config may not be a symbolic link: {name}")
                else:
                    issues.extend(_verify_venv_config(path, root=root, provider_target=provider_target))
            elif kind == "provider-alias":
                if provider_target is None or not path.is_symlink() or path.resolve(strict=False) != provider_target:
                    issues.append(f"managed runtime provider alias mismatch: {name}")
            elif kind == "lib-alias":
                if not path.is_symlink() or path.resolve(strict=False) != (root / "lib").resolve(strict=False):
                    issues.append(f"managed runtime lib alias mismatch: {name}")
            continue
        if name in expected_names:
            continue
        if _is_bytecode_cache(relative):
            # Already reported by the complete-tree scan above.  Keep this
            # branch explicit so a future exclusion change cannot reintroduce
            # the original verification bypass.
            continue
        if _is_excluded(relative):
            continue
        if path.is_file() and os.access(path, os.X_OK):
            issues.append(f"unexpected executable in managed runtime: {name}")
        else:
            issues.append(f"unexpected managed runtime file: {name}")
    return sorted(set(issues))


def _validate_runtime_inventory(runtime: Mapping[str, Any]) -> None:
    if runtime.get("schema_version") != RUNTIME_INVENTORY_SCHEMA:
        raise ContractError("Signed runtime inventory has an unsupported schema.")
    if runtime.get("digest") != _inventory_digest(runtime):
        raise ContractError("Signed runtime inventory digest is invalid.")
    profile = runtime.get("profile")
    if not isinstance(profile, str) or not profile:
        raise ContractError("Signed runtime inventory profile is missing.")
    wheels = runtime.get("wheels")
    if not isinstance(wheels, list):
        raise ContractError("Signed runtime inventory wheels must be a list.")
    for wheel in wheels:
        if not isinstance(wheel, Mapping):
            raise ContractError("Signed runtime inventory wheel is malformed.")
        _validate_hash_row(wheel, label="signed runtime wheel")
        install_paths: set[str] = set()
        for member in list(wheel.get("files", []) or []):
            if not isinstance(member, Mapping):
                raise ContractError("Signed runtime inventory member is malformed.")
            _validate_hash_row(member, label="signed runtime member")
            if not isinstance(member.get("executable"), bool):
                raise ContractError("Signed runtime member executable identity is missing.")
            member_path = _safe_relative(member.get("path", ""), label="signed runtime member")
            _reject_bytecode_cache(member_path, label="Signed runtime member")
            install_path = _safe_relative(member.get("install_path", ""), label="signed runtime member install path")
            if install_path.as_posix() in install_paths:
                raise ContractError(f"Signed runtime wheel has duplicate install path: {install_path}")
            install_paths.add(install_path.as_posix())
            install_path_text = install_path.as_posix()
            if install_path_text.startswith("scripts/"):
                installed_bytes = member.get("installed_bytes")
                installed_sha = member.get("installed_sha256")
                if isinstance(installed_bytes, bool) or not isinstance(installed_bytes, int) or installed_bytes < 0:
                    raise ContractError("Signed runtime script installed byte count is invalid.")
                if not isinstance(installed_sha, str) or not re.fullmatch(r"[0-9a-f]{64}", installed_sha):
                    raise ContractError("Signed runtime script installed SHA-256 is invalid.")
                if not isinstance(member.get("pip_placeholder_shebang"), bool):
                    raise ContractError("Signed runtime script shebang policy is missing.")
        generated_scripts = wheel.get("generated_scripts", [])
        if not isinstance(generated_scripts, list):
            raise ContractError("Signed runtime generated_scripts must be a list.")
        for script in generated_scripts:
            if not isinstance(script, Mapping) or not re.fullmatch(
                r"[A-Za-z0-9_.-]+", str(script.get("name", ""))
            ):
                raise ContractError("Signed runtime generated script is malformed.")
            script_path = _safe_relative(script.get("install_path", ""), label="signed runtime generated script")
            if not script_path.as_posix().startswith("scripts/"):
                raise ContractError("Signed runtime generated script must install under scripts/.")
            if script_path.as_posix() in install_paths:
                raise ContractError(f"Signed runtime wheel has duplicate generated install path: {script_path}")
            install_paths.add(script_path.as_posix())
            installed_bytes = script.get("installed_bytes")
            installed_sha = script.get("installed_sha256")
            if isinstance(installed_bytes, bool) or not isinstance(installed_bytes, int) or installed_bytes < 0:
                raise ContractError("Signed runtime generated script byte count is invalid.")
            if not isinstance(installed_sha, str) or not re.fullmatch(r"[0-9a-f]{64}", installed_sha):
                raise ContractError("Signed runtime generated script SHA-256 is invalid.")
            if not isinstance(script.get("executable"), bool):
                raise ContractError("Signed runtime generated script executable identity is missing.")
        _safe_relative(wheel.get("record", ""), label="signed runtime RECORD")
    layout = runtime.get("layout")
    if not isinstance(layout, Mapping):
        raise ContractError("Signed runtime layout is malformed.")
    _safe_relative(layout.get("interpreter", ""), label="signed runtime interpreter")
    provider = layout.get("provider")
    if not isinstance(provider, Mapping) or not str(provider.get("boundary", "")):
        raise ContractError("Signed runtime provider boundary is missing.")
    interpreter_file = layout.get("interpreter_file")
    if interpreter_file is not None:
        if not isinstance(interpreter_file, Mapping):
            raise ContractError("Signed runtime interpreter file identity is malformed.")
        _validate_hash_row(interpreter_file, label="signed runtime interpreter")
    extras = layout.get("extras")
    if not isinstance(extras, list):
        raise ContractError("Signed runtime layout extras are malformed.")
    seen_extras: set[str] = set()
    for extra in extras:
        if not isinstance(extra, Mapping):
            raise ContractError("Signed runtime layout extra is malformed.")
        path = _safe_relative(extra.get("path", ""), label="signed runtime layout extra")
        if path.as_posix() in seen_extras:
            raise ContractError(f"Signed runtime layout extra is duplicated: {path}")
        seen_extras.add(path.as_posix())
        kind = str(extra.get("kind", ""))
        if kind not in {"venv-config", "provider-alias", "lib-alias"}:
            raise ContractError(f"Signed runtime layout extra has unsupported kind: {kind!r}")
        if kind == "venv-config" and extra.get("include_system_site_packages") is not False:
            raise ContractError("Signed runtime venv config must disable system site packages.")
        if kind == "provider-alias" and str(extra.get("provider_boundary", "")) != str(provider.get("boundary")):
            raise ContractError("Signed runtime provider alias is not bound to its provider boundary.")
        if kind == "lib-alias" and (path.as_posix() != "lib64" or str(extra.get("target", "")) != "lib"):
            raise ContractError("Signed runtime lib alias must bind lib64 to lib.")
